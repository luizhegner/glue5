//! Generates the C glue (import forwarders, Emscripten setjmp/longjmp, export
//! wrappers, hooks) and the matching Rust bindings.

use std::fmt::Write as _;

use anyhow::{Context, Result, bail, ensure};

use crate::mangle::{game_symbol, import_symbol};
use crate::module::{Module, Sig, Ty};

/// A hook resolved against the module.
pub struct Hook {
    pub field: String,
    pub symbol: String,
    pub sig: Sig,
    /// Only called by the host: not renamed, no stub, no field in `Hooks`.
    pub called_only: bool,
}

pub fn resolve_hooks(module: &Module, list: &[(&str, &str)], called_only: &[&str]) -> Result<Vec<Hook>> {
    if let Some(field) = called_only.iter().find(|&&f| !list.iter().any(|&(field, _)| field == f)) {
        bail!("`{field}` is called only, but is no hook");
    }
    // One entry per field and per function: a function under two fields
    // (one taken over, one called only, say) would be renamed for one of
    // them only.
    let (mut fields, mut functions) = (std::collections::HashSet::new(), std::collections::HashMap::new());
    for &(field, name) in list {
        ensure!(fields.insert(field), "hook field `{field}` is listed twice");
        if let Some(other) = functions.insert(name, field) {
            bail!("`{name}` is listed as both `{other}` and `{field}`");
        }
    }
    list.iter()
        .map(|&(field, name)| {
            ensure!(is_ident(field), "hook field `{field}` is not an identifier");
            let sig = module
                .functions
                .get(name)
                .with_context(|| format!("hook `{field}`: no function named `{name}` in game.wasm"))?;
            ensure!(sig.crosses_boundary_ok(), "hook `{field}`: v128 parameters are not supported");
            let called_only = called_only.contains(&field);
            Ok(Hook { field: field.into(), symbol: game_symbol(name), sig: sig.clone(), called_only })
        })
        .collect()
}

/// Imports implemented in C here rather than by the host.
fn is_c_import(name: &str) -> bool {
    name.starts_with("invoke_") || name == "_emscripten_throw_longjmp"
}

pub fn glue_c(module: &Module, hooks: &[Hook]) -> Result<String> {
    for (what, sig) in
        module.imports.iter().map(|i| (&i.name, &i.sig)).chain(module.exports.iter().map(|e| (&e.name, &e.sig)))
    {
        ensure!(sig.crosses_boundary_ok(), "`{what}` has v128 in its signature");
    }
    let mut c = String::new();
    c += "/* Generated by glue5-game/build. Do not edit. */\n";
    c += "#include <stdio.h>\n#include <stdlib.h>\n#include <string.h>\n\n";
    c += "#include \"game.h\"\n#include \"glue5.h\"\n";
    c += "#include \"wasm-rt-exceptions.h\"\n#include \"wasm-rt-impl.h\"\n\n";

    // Imports: a table of host function pointers, filled by Rust.
    c += "typedef struct glue5_imports {\n";
    for import in host_imports(module) {
        let _ = writeln!(c, "  {} (*{})({});", c_ret(&import.sig), import.name, c_params(&import.sig));
    }
    c += "} glue5_imports;\n\nglue5_imports glue5_imports_table;\n\n";
    for import in host_imports(module) {
        let sym = import_symbol(&import.module, &import.name);
        let (self_ty, env) = match import.module.as_str() {
            "env" => ("struct w2c_env*", "self"),
            "wasi_snapshot_preview1" => ("struct w2c_wasi__snapshot__preview1*", "&self->env"),
            other => bail!("unexpected import module `{other}`"),
        };
        let _ = writeln!(
            c,
            "{} {sym}({self_ty} self{}) {{\n  {}glue5_imports_table.{}({env}{});\n}}",
            c_ret(&import.sig),
            c_named_params(&import.sig.params, 0),
            ret_kw(&import.sig),
            import.name,
            args(import.sig.params.len(), 0),
        );
    }

    // Emscripten's setjmp/longjmp: invoke_* calls a table function inside a
    // setjmp frame; _emscripten_throw_longjmp jumps back to it.
    let export_sym = |name: &str| -> Result<String> {
        ensure!(module.exports.iter().any(|e| e.name == name), "game.wasm does not export `{name}`");
        Ok(game_symbol(name))
    };
    let stack_get = export_sym("emscripten_stack_get_current")?;
    let stack_restore = export_sym("_emscripten_stack_restore")?;
    let set_threw = export_sym("setThrew")?;
    // Table exports are accessors, not functions: not in `module.exports`.
    let table = game_symbol("__indirect_function_table");
    for import in module.imports.iter().filter(|i| i.module == "env" && is_c_import(&i.name)) {
        let sym = import_symbol("env", &import.name);
        if import.name == "_emscripten_throw_longjmp" {
            let _ = writeln!(c, "\nvoid {sym}(struct w2c_env* env) {{\n  glue5_longjmp(env);\n}}");
            continue;
        }
        let sig = &import.sig;
        ensure!(sig.params.first() == Some(&Ty::I64), "{}: expected an i64 table index", import.name);
        let callee = Sig { params: sig.params[1..].to_vec(), result: sig.result };
        let _ = writeln!(c, "\n{} {sym}(struct w2c_env* env{}) {{", c_ret(sig), c_named_params(&sig.params, 0));
        if let Some(ret) = sig.result {
            let _ = writeln!(c, "  volatile {} result = 0;", c_ty(ret));
        }
        let _ = writeln!(
            c,
            "  wasm_rt_funcref_table_t* table = {table}(env->instance);\n  \
             if (p0 >= table->size || !table->data[p0].func) {{\n    \
             fprintf(stderr, \"glue5: {}: bad function index %llu\\n\", (unsigned long long)p0);\n    \
             abort();\n  }}\n  \
             const wasm_rt_funcref_t* f = &table->data[p0];\n  \
             void* prev = env->longjmp_target;\n  \
             u64 sp = {stack_get}(env->instance);\n  \
             jmp_buf frame;\n  \
             env->longjmp_target = &frame;\n  \
             if (GLUE5_SETJMP(frame) == 0) {{",
            import.name
        );
        let call = format!(
            "(({} (*)(void*{}))f->func)(env->instance{})",
            c_ret(&callee),
            callee.params.iter().map(|&t| format!(", {}", c_ty(t))).collect::<String>(),
            args(sig.params.len(), 1),
        );
        if sig.result.is_some() {
            let _ = writeln!(c, "    result = {call};");
        } else {
            let _ = writeln!(c, "    {call};");
        }
        let _ = writeln!(
            c,
            "  }} else {{\n    {stack_restore}(env->instance, sp);\n    {set_threw}(env->instance, 1, 0);\n  }}\n  \
             env->longjmp_target = prev;"
        );
        if sig.result.is_some() {
            c += "  return result;\n";
        }
        c += "}\n";
    }

    // Exports: called from Rust inside a trap boundary.
    c += "\n";
    for export in &module.exports {
        let sym = game_symbol(&export.name);
        let out = export.sig.result.map(|t| format!(", {}* out", c_ty(t))).unwrap_or_default();
        let assign = if export.sig.result.is_some() { "*out = " } else { "" };
        let _ = writeln!(
            c,
            "uint32_t glue5_export_{}(struct w2c_env* env{}{out}) {{\n  GLUE5_TRY({assign}{sym}(env->instance{}));\n}}",
            export.name,
            c_named_params(&export.sig.params, 0),
            args(export.sig.params.len(), 0),
        );
    }

    // Hooks: the original definition is renamed to *_orig (see main.rs);
    // these take its place. Those only called keep their definition, which
    // the host calls directly.
    c += "\ntypedef struct glue5_hooks {\n";
    for hook in hooks.iter().filter(|h| !h.called_only) {
        let _ = writeln!(c, "  {} (*{})({});", c_ret(&hook.sig), hook.field, c_params(&hook.sig));
    }
    if hooks.iter().all(|h| h.called_only) {
        c += "  char unused;\n";
    }
    c += "} glue5_hooks;\n\nglue5_hooks glue5_hooks_table;\n";
    for hook in hooks {
        let (sym, sig, field) = (&hook.symbol, &hook.sig, &hook.field);
        let params = c_named_params(&sig.params, 0);
        let a = args(sig.params.len(), 0);
        let ret = ret_kw(sig);
        if hook.called_only {
            let _ = writeln!(
                c,
                "\n{} {sym}(w2c_game* instance{params});\n\
                 {} glue5_orig_{field}(struct w2c_env* env{params}) {{\n  {ret}{sym}(env->instance{a});\n}}",
                c_ret(sig),
                c_ret(sig),
            );
            continue;
        }
        let _ = writeln!(
            c,
            "\n{} {sym}_orig(w2c_game* instance{params});\n\
             {} {sym}(w2c_game* instance{params}) {{\n  \
             if (glue5_hooks_table.{field}) {{\n    \
             {ret}glue5_hooks_table.{field}(instance->w2c_env_instance{a});\n    {}\n  }}\n  \
             {ret}{sym}_orig(instance{a});\n}}\n\
             {} glue5_orig_{field}(struct w2c_env* env{params}) {{\n  {ret}{sym}_orig(env->instance{a});\n}}",
            c_ret(sig),
            c_ret(sig),
            if sig.result.is_some() { "" } else { "return;" },
            c_ret(sig),
        );
    }
    Ok(c)
}

pub fn bindings_rs(module: &Module, hooks: &[Hook]) -> String {
    let mut r = String::new();
    r += "// Generated by glue5-game/build from game.wasm. Do not edit.\n\n";
    let _ = writeln!(r, "/// Initial size of the module's memory, in 64 KiB pages.");
    let _ = writeln!(r, "pub const MEMORY_INITIAL_PAGES: u64 = {};", module.memory.initial_pages);
    let _ = writeln!(r, "/// Maximum size of the module's memory, in 64 KiB pages.");
    let _ = writeln!(r, "pub const MEMORY_MAX_PAGES: u64 = {};\n", module.memory.max_pages);

    r += "/// Host implementations of the module's imports. Build it with\n";
    r += "/// [`imports_from!`](crate::imports_from) from a module that defines one\n";
    r += "/// function per import.\n#[repr(C)]\npub struct Imports {\n";
    for import in host_imports(module) {
        let _ = writeln!(r, "    /// `{}.{}`", import.module, import.name);
        let _ = writeln!(r, "    pub {}: {},", import.name, rs_fn(&import.sig));
    }
    r += "}\n\n";

    r += "/// Builds [`Imports`] from a module with one function per import, named\n";
    r += "/// like the import.\n#[macro_export]\nmacro_rules! imports_from {\n    ($m:ident) => {\n        $crate::Imports {\n";
    for import in host_imports(module) {
        let _ = writeln!(r, "            {0}: $m::{0},", import.name);
    }
    r += "        }\n    };\n}\n\n";

    r += "/// Host replacements for game functions (see hooks.rs). `None` keeps the original.\n";
    r += "#[repr(C)]\n#[derive(Clone, Copy, Default)]\npub struct Hooks {\n";
    for hook in hooks.iter().filter(|h| !h.called_only) {
        let _ = writeln!(r, "    pub {}: Option<{}>,", hook.field, rs_fn(&hook.sig));
    }
    if hooks.iter().all(|h| h.called_only) {
        r += "    _unused: u8,\n";
    }
    r += "}\n\n";

    r += "unsafe extern \"C\" {\n    pub(crate) static mut glue5_imports_table: Imports;\n    pub(crate) static mut glue5_hooks_table: Hooks;\n}\n\n";

    r += "/// The original implementations of hooked functions.\npub mod orig {\n    use super::Env;\n    unsafe extern \"C\" {\n";
    for hook in hooks {
        let _ = writeln!(
            r,
            "        #[link_name = \"glue5_orig_{}\"]\n        pub fn {}(env: *mut Env{}){};",
            hook.field,
            hook.field,
            rs_params(&hook.sig.params),
            rs_ret(&hook.sig)
        );
    }
    r += "    }\n}\n\n";

    r += "/// The module's exported functions. Each call is a trap boundary.\npub mod exports {\n";
    r += "    use super::{Env, Trap};\n\n    unsafe extern \"C\" {\n";
    for export in &module.exports {
        let out = export.sig.result.map(|t| format!(", out: *mut {}", rs_ty(t))).unwrap_or_default();
        let _ = writeln!(
            r,
            "        fn glue5_export_{}(env: *mut Env{}{out}) -> u32;",
            export.name,
            rs_params(&export.sig.params)
        );
    }
    r += "    }\n";
    for export in &module.exports {
        let names = (0..export.sig.params.len()).map(|i| format!(", p{i}")).collect::<String>();
        match export.sig.result {
            Some(t) => {
                let _ = writeln!(
                    r,
                    "\n    /// # Safety\n    /// `env` must be a live instance's environment on this thread.\n    \
                     pub unsafe fn {0}(env: *mut Env{1}) -> Result<{2}, Trap> {{\n        \
                     let mut out: {2} = Default::default();\n        \
                     Trap::check(unsafe {{ glue5_export_{0}(env{3}, &mut out) }}).map(|()| out)\n    }}",
                    export.name,
                    rs_params(&export.sig.params),
                    rs_ty(t),
                    names
                );
            }
            None => {
                let _ = writeln!(
                    r,
                    "\n    /// # Safety\n    /// `env` must be a live instance's environment on this thread.\n    \
                     pub unsafe fn {0}(env: *mut Env{1}) -> Result<(), Trap> {{\n        \
                     Trap::check(unsafe {{ glue5_export_{0}(env{2}) }})\n    }}",
                    export.name,
                    rs_params(&export.sig.params),
                    names
                );
            }
        }
    }
    r += "}\n";
    r
}

fn host_imports(module: &Module) -> impl Iterator<Item = &crate::module::Import> {
    module.imports.iter().filter(|i| !(i.module == "env" && is_c_import(&i.name)))
}

fn is_ident(s: &str) -> bool {
    !s.is_empty()
        && !s.starts_with(|c: char| c.is_ascii_digit())
        && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
}

fn c_ty(t: Ty) -> &'static str {
    match t {
        Ty::I32 => "u32",
        Ty::I64 => "u64",
        Ty::F32 => "f32",
        Ty::F64 => "f64",
        Ty::V128 => "v128",
    }
}

fn rs_ty(t: Ty) -> &'static str {
    c_ty(t) // u32/u64/f32/f64 are the same names in Rust
}

fn c_ret(sig: &Sig) -> &'static str {
    sig.result.map_or("void", c_ty)
}

fn ret_kw(sig: &Sig) -> &'static str {
    if sig.result.is_some() { "return " } else { "" }
}

/// `struct w2c_env*, u32, u64` (prototype without names).
fn c_params(sig: &Sig) -> String {
    let mut s = String::from("struct w2c_env*");
    for &t in &sig.params {
        s += ", ";
        s += c_ty(t);
    }
    s
}

/// `, u32 p0, u64 p1` (continuing a parameter list).
fn c_named_params(params: &[Ty], first: usize) -> String {
    params.iter().enumerate().map(|(i, &t)| format!(", {} p{}", c_ty(t), i + first)).collect()
}

/// `, p<from>, p<from+1>, ...` for `n` parameters starting at index `from`.
fn args(n: usize, from: usize) -> String {
    (from..n).map(|i| format!(", p{i}")).collect()
}

fn rs_params(params: &[Ty]) -> String {
    params.iter().enumerate().map(|(i, &t)| format!(", p{i}: {}", rs_ty(t))).collect()
}

fn rs_ret(sig: &Sig) -> String {
    sig.result.map(|t| format!(" -> {}", rs_ty(t))).unwrap_or_default()
}

fn rs_fn(sig: &Sig) -> String {
    let params: String = sig.params.iter().map(|&t| format!(", {}", rs_ty(t))).collect();
    format!("unsafe extern \"C\" fn(*mut Env{params}){}", rs_ret(sig))
}
